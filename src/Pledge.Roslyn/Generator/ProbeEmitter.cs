using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace PledgeContracts.Roslyn.Generator;

// Writes the testing bridge's view of one contracted method: a probe that runs every contract around one call and
// reports a PledgeOutcome instead of throwing, and a module initializer that registers it with PledgeRegistry.
// Probes check every contract whatever the modes, since a property test is the point where all of them matter, and
// they call the original method directly: generated code is not intercepted.
internal static class ProbeEmitter
{
    private const string Runtime = "global::PledgeContracts.";
    private const string CatchAll = "global::System.Exception";

    public static string HintName(ContractedMethod method) => method.ClassName + ".Probe.g.cs";

    public static string Emit(ContractedMethod method)
    {
        var builder = new StringBuilder();
        var className = method.ClassName + "_Probe";

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine($"// Pledge testing probe for {method.MemberName}. Edits are lost on the next build.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        foreach (var directive in method.Usings)
        {
            builder.AppendLine(directive);
        }

        builder.AppendLine();
        builder.AppendLine($"namespace {WrapperEmitter.Namespace}");
        builder.AppendLine("{");
        builder.AppendLine($"    file static class {className}");
        builder.AppendLine("    {");
        AppendRegistration(builder, method);

        if (method.ProbeUnsupportedReason is null)
        {
            builder.AppendLine();
            AppendProbe(builder, method);
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendRegistration(StringBuilder builder, ContractedMethod method)
    {
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("        {");
        builder.AppendLine($"            {Runtime}PledgeRegistry.Register(new {Runtime}PledgedMember(");
        builder.AppendLine($"                typeof({method.ContainingType}),");
        builder.AppendLine($"                {Literal(method.MethodName)},");
        builder.AppendLine($"                {Literal(method.Signature)},");
        builder.AppendLine($"                {(method.IsStatic ? "true" : "false")},");
        builder.AppendLine($"                {(method.ResultTypeOf is null ? "null" : $"typeof({method.ResultTypeOf})")},");
        builder.AppendLine($"                new {Runtime}PledgedParameter[]");
        builder.AppendLine("                {");
        foreach (var parameter in method.Parameters)
        {
            var direction = parameter.RefKind switch
            {
                Microsoft.CodeAnalysis.RefKind.Ref => "Ref",
                Microsoft.CodeAnalysis.RefKind.Out => "Out",
                _ => "Value",
            };
            builder.AppendLine($"                    new {Runtime}PledgedParameter({Literal(parameter.Name)}, typeof({parameter.TypeOf}), {Runtime}PledgedParameterDirection.{direction}, {(parameter.AllowsNull ? "true" : "false")}),");
        }

        builder.AppendLine("                },");
        builder.AppendLine($"                new {Runtime}PledgedContract[]");
        builder.AppendLine("                {");
        foreach (var contract in method.Contracts)
        {
            var exceptionType = contract.ExceptionType is null ? "null" : $"typeof({contract.ExceptionType})";
            builder.AppendLine($"                    new {Runtime}PledgedContract({Runtime}PledgeKind.{contract.PledgeKind}, {Literal(contract.Text)}, {exceptionType}),");
        }

        builder.AppendLine("                },");
        if (method.ProbeUnsupportedReason is null)
        {
            builder.AppendLine("                Probe));");
        }
        else
        {
            builder.AppendLine("                null,");
            builder.AppendLine($"                {Literal(method.ProbeUnsupportedReason)}));");
        }

        builder.AppendLine("        }");
    }

    private static void AppendProbe(StringBuilder builder, ContractedMethod method)
    {
        var isAsync = method.AsyncKind != AsyncKind.None;
        var outcome = $"{Runtime}PledgeOutcome";
        var signature = $"(object? __receiver, object?[] __arguments)";

        if (isAsync)
        {
            builder.AppendLine($"        private static async global::System.Threading.Tasks.ValueTask<{outcome}> Probe{signature}");
            builder.AppendLine("        {");
            AppendBody(builder, method, awaitKeyword: "await ");
            builder.AppendLine("        }");
        }
        else
        {
            builder.AppendLine($"        private static global::System.Threading.Tasks.ValueTask<{outcome}> Probe{signature} => new(Run(__receiver, __arguments));");
            builder.AppendLine();
            builder.AppendLine($"        private static {outcome} Run{signature}");
            builder.AppendLine("        {");
            AppendBody(builder, method, awaitKeyword: string.Empty);
            builder.AppendLine("        }");
        }

        builder.AppendLine();
        builder.AppendLine($"        private static {Runtime}PledgeViolation Violation({Runtime}PledgeKind kind, string expression, string? message, global::System.Exception? thrown = null, global::System.Exception? cause = null) => new {Runtime}PledgeViolation");
        builder.AppendLine("        {");
        builder.AppendLine("            Kind = kind,");
        builder.AppendLine("            Expression = expression,");
        builder.AppendLine($"            Member = {Literal(method.MemberName)},");
        builder.AppendLine("            Message = message,");
        builder.AppendLine("            Thrown = thrown,");
        builder.AppendLine("            Cause = cause,");
        builder.AppendLine("        };");
    }

    private static void AppendBody(StringBuilder builder, ContractedMethod method, string awaitKeyword)
    {
        const string Indent = "            ";
        var outcome = $"{Runtime}PledgeOutcome";

        if (!method.IsStatic)
        {
            builder.AppendLine($"{Indent}var @this = ({method.ContainingType})__receiver!;");
        }

        for (var i = 0; i < method.Parameters.Count; i++)
        {
            var parameter = method.Parameters[i];
            builder.AppendLine(parameter.RefKind == Microsoft.CodeAnalysis.RefKind.Out
                ? $"{Indent}{parameter.Type} {parameter.Name} = default!;"
                : $"{Indent}{parameter.Type} {parameter.Name} = ({parameter.Type})__arguments[{i}]!;");
        }

        builder.AppendLine();
        foreach (var contract in method.Contracts.Where(contract => contract.Kind == ContractKind.Precondition))
        {
            AppendCheck(builder, contract, onFalse: "Rejected", thrown: null, Indent);
        }

        foreach (var snapshot in method.Snapshots)
        {
            builder.AppendLine($"{Indent}{snapshot.Type} {snapshot.Name} = ({snapshot.Expression});");
        }

        var arguments = string.Join(", ", method.Parameters.Select(p => p.Argument));
        var call = $"{awaitKeyword}{(method.IsStatic ? method.ContainingType : "@this")}.{method.MethodName}({arguments})";
        if (method.HasResult)
        {
            builder.AppendLine($"{Indent}{method.ResultType} __result;");
        }

        builder.AppendLine($"{Indent}try");
        builder.AppendLine($"{Indent}{{");
        builder.AppendLine(method.HasResult ? $"{Indent}    __result = {call};" : $"{Indent}    {call};");
        builder.AppendLine($"{Indent}}}");

        var onThrow = method.Contracts.Where(contract => contract.Kind == ContractKind.PostconditionOnThrow).ToList();
        if (onThrow.Count > 0 && !method.OnThrowCoversCancellation)
        {
            builder.AppendLine($"{Indent}catch (global::System.OperationCanceledException __pledgeCancelled)");
            builder.AppendLine($"{Indent}{{");
            builder.AppendLine($"{Indent}    return {outcome}.Threw(__pledgeCancelled, false);");
            builder.AppendLine($"{Indent}}}");
        }

        foreach (var clause in onThrow.GroupBy(contract => contract.ExceptionType!, StringComparer.Ordinal).OrderByDescending(group => group.First().ExceptionDepth).ThenBy(group => group.Key, StringComparer.Ordinal))
        {
            builder.AppendLine($"{Indent}catch ({clause.Key} __pledgeThrown)");
            builder.AppendLine($"{Indent}{{");
            foreach (var contract in clause)
            {
                AppendCheck(builder, contract, onFalse: "Broken", thrown: "__pledgeThrown", Indent + "    ");
            }

            builder.AppendLine($"{Indent}    return {outcome}.Threw(__pledgeThrown, true);");
            builder.AppendLine($"{Indent}}}");
        }

        // An EnsuresOnThrow<Exception> clause already catches everything, and a second catch-all would not compile.
        if (!onThrow.Any(contract => contract.ExceptionType == CatchAll))
        {
            builder.AppendLine($"{Indent}catch (global::System.Exception __pledgeEscaped)");
            builder.AppendLine($"{Indent}{{");
            builder.AppendLine($"{Indent}    return {outcome}.Threw(__pledgeEscaped, false);");
            builder.AppendLine($"{Indent}}}");
        }

        builder.AppendLine();

        foreach (var contract in method.Contracts.Where(contract => contract.Kind == ContractKind.Postcondition))
        {
            AppendCheck(builder, contract, onFalse: "Broken", thrown: null, Indent);
        }

        builder.AppendLine($"{Indent}return {outcome}.Kept({(method.HasResult ? "__result" : "null")});");
    }

    // A contract that evaluates to false yields onFalse (Rejected for preconditions, Broken otherwise); one that throws
    // is always Broken, with the exception as the cause, because the contract itself is then at fault.
    private static void AppendCheck(StringBuilder builder, ContractModel contract, string onFalse, string? thrown, string indent)
    {
        var ok = "__pledgeOk" + contract.Index;
        var kind = $"{Runtime}PledgeKind.{contract.PledgeKind}";
        var text = Literal(contract.Text);
        var thrownArgument = thrown ?? "null";

        builder.AppendLine($"{indent}bool {ok};");
        builder.AppendLine($"{indent}try");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    {ok} = ({contract.Expression});");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine($"{indent}catch (global::System.Exception __pledgeCause)");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    return {Runtime}PledgeOutcome.Broken(Violation({kind}, {text}, null, {thrownArgument}, __pledgeCause));");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine();
        builder.AppendLine($"{indent}if (!{ok})");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    return {Runtime}PledgeOutcome.{onFalse}(Violation({kind}, {text}, {contract.Message ?? "null"}, {thrownArgument}));");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
