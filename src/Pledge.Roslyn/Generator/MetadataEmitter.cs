using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace PledgeContracts.Roslyn.Generator;

// The declarative view of every contract in the assembly, as assembly-level attributes from Pledge.Attributes.
// A generator cannot add attributes to members it did not declare, so the member is named by type and signature.
internal static class MetadataEmitter
{
    public const string HintName = "PledgeContracts.Metadata.g.cs";

    public static string? Emit(IEnumerable<ContractedMethod> methods)
    {
        var builder = new StringBuilder();
        var any = false;

        foreach (var method in methods.Where(method => method.Problems.Count == 0).OrderBy(method => method.ContainingType, StringComparer.Ordinal).ThenBy(method => method.Signature, StringComparer.Ordinal))
        {
            var target = $"typeof({method.ContainingType}), {Literal(method.Signature)}";
            foreach (var contract in method.Contracts)
            {
                any = true;
                builder.AppendLine(contract.Kind switch
                {
                    ContractKind.Precondition => $"[assembly: global::PledgeContracts.Requires({target}, {Literal(contract.Text)})]",
                    ContractKind.Postcondition => $"[assembly: global::PledgeContracts.Ensures({target}, {Literal(contract.Text)})]",
                    _ => $"[assembly: global::PledgeContracts.EnsuresOnThrow({target}, typeof({contract.ExceptionType}), {Literal(contract.Text)})]",
                });
            }
        }

        if (!any)
        {
            return null;
        }

        return "// <auto-generated/>\n// Declarative view of every contract in this assembly, for documentation tools and analyzers in other assemblies.\n#pragma warning disable\n" + builder;
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
