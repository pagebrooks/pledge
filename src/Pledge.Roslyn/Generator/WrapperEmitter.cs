using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace PledgeContracts.Roslyn.Generator;

// Writes the checked wrapper for one contracted method: a shared __Checked body that runs the contracts and then
// calls the original, plus one tiny interceptor stub per call site whose #line directive hands the caller's
// file and line to __Checked through [CallerFilePath]/[CallerLineNumber].
internal static class WrapperEmitter
{
    public const string Namespace = "PledgeContracts.Generated";

    public static string Emit(ContractedMethod method, IReadOnlyList<CallSite> callSites, PledgeMode mode)
    {
        var builder = new StringBuilder();
        var report = "global::PledgeContracts.PledgeRuntime." + PledgeModes.ReportMethod(mode);
        var returnKeyword = method.ReturnsVoid ? string.Empty : "return ";
        var parameters = string.Join(", ", method.Parameters.Select(p => p.Declaration));
        var arguments = string.Join(", ", method.Parameters.Select(p => p.Argument));
        var receiverParameter = method.IsStatic ? string.Empty : method.ContainingType + " @this";
        var checkedParameters = Join(receiverParameter, parameters);
        var checkedArguments = Join(method.IsStatic ? string.Empty : "@this", arguments);
        var target = method.IsStatic ? method.ContainingType : "@this";

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine($"// Pledge contract checks for {method.MemberName}. Edits are lost on the next build.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        foreach (var directive in method.Usings)
        {
            builder.AppendLine(directive);
        }

        builder.AppendLine();
        builder.AppendLine($"namespace {Namespace}");
        builder.AppendLine("{");
        builder.AppendLine($"    file static class {method.ClassName}");
        builder.AppendLine("    {");

        for (var i = 0; i < callSites.Count; i++)
        {
            var site = callSites[i];
            builder.AppendLine("        [global::System.Diagnostics.DebuggerStepThrough]");
            builder.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({site.Version}, {Literal(site.Data)})]");
            builder.AppendLine($"        public static {method.ReturnType} __Intercept{i}({Join(method.IsStatic ? string.Empty : "this " + receiverParameter, parameters)})");
            builder.AppendLine("        {");
            builder.AppendLine($"#line {site.Line} \"{site.FilePath}\"");
            builder.AppendLine($"            {returnKeyword}__Checked({checkedArguments});");
            builder.AppendLine("#line default");
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        builder.AppendLine($"        private static {method.ReturnType} __Checked({Join(checkedParameters, "[global::System.Runtime.CompilerServices.CallerFilePath] string __callerFilePath = \"\", [global::System.Runtime.CompilerServices.CallerLineNumber] int __callerLineNumber = 0")})");
        builder.AppendLine("        {");

        for (var i = 0; i < method.Contracts.Count; i++)
        {
            AppendCheck(builder, method, method.Contracts[i], i, report);
        }

        builder.AppendLine($"            {returnKeyword}{target}.{method.MethodName}({arguments});");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("namespace System.Runtime.CompilerServices");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        builder.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute");
        builder.AppendLine("    {");
        builder.AppendLine("        public InterceptsLocationAttribute(int version, string data)");
        builder.AppendLine("        {");
        builder.AppendLine("            _ = version;");
        builder.AppendLine("            _ = data;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static void AppendCheck(StringBuilder builder, ContractedMethod method, ContractModel contract, int index, string report)
    {
        var ok = "__pledgeOk" + index;
        var line = $"#line {contract.Site.Line} \"{contract.Site.FilePath}\"";

        builder.AppendLine($"            bool {ok};");
        builder.AppendLine("            try");
        builder.AppendLine("            {");
        builder.AppendLine(line);
        builder.AppendLine($"                {ok} = ({contract.Expression});");
        builder.AppendLine("#line default");
        builder.AppendLine("            }");
        builder.AppendLine("            catch (global::System.Exception __pledgeCause)");
        builder.AppendLine("            {");
        AppendReport(builder, method, contract, report, cause: "__pledgeCause");
        builder.AppendLine($"                {ok} = true;");
        builder.AppendLine("            }");
        builder.AppendLine();
        builder.AppendLine($"            if (!{ok})");
        builder.AppendLine("            {");
        builder.AppendLine(line);
        AppendReport(builder, method, contract, report, cause: null);
        builder.AppendLine("#line default");
        builder.AppendLine("            }");
        builder.AppendLine();
    }

    private static void AppendReport(StringBuilder builder, ContractedMethod method, ContractModel contract, string report, string? cause)
    {
        builder.AppendLine($"                {report}(new global::PledgeContracts.PledgeViolation");
        builder.AppendLine("                {");
        builder.AppendLine($"                    Kind = global::PledgeContracts.PledgeKind.{contract.Kind},");
        builder.AppendLine($"                    Expression = {Literal(contract.Text)},");
        builder.AppendLine($"                    Member = {Literal(method.MemberName)},");
        builder.AppendLine($"                    Message = {contract.Message ?? "null"},");
        builder.AppendLine("                    CallerFilePath = __callerFilePath,");
        builder.AppendLine("                    CallerLineNumber = __callerLineNumber,");
        if (cause is not null)
        {
            builder.AppendLine($"                    Cause = {cause},");
        }

        builder.AppendLine("                });");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Join(string left, string right) =>
        left.Length == 0 ? right : right.Length == 0 ? left : left + ", " + right;
}
