using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace PledgeContracts.Roslyn.Generator;

// Writes the checked wrapper for one contracted method: a shared __Checked body that runs the preconditions, takes
// the Old snapshots, calls the original and runs the postconditions, plus one tiny interceptor stub per call site
// whose #line directive hands the caller's file and line to __Checked through [CallerFilePath]/[CallerLineNumber].
// Async methods split the part after the snapshots into an async __Awaited so preconditions still throw synchronously.
internal static class WrapperEmitter
{
    public const string Namespace = "PledgeContracts.Generated";

    private const string CallerParameters =
        "[global::System.Runtime.CompilerServices.CallerFilePath] string __callerFilePath = \"\", [global::System.Runtime.CompilerServices.CallerLineNumber] int __callerLineNumber = 0";

    public static string Emit(ContractedMethod method, IReadOnlyList<CallSite> callSites, PledgeMode mode)
    {
        var builder = new StringBuilder();
        var report = "global::PledgeContracts.PledgeRuntime." + PledgeModes.ReportMethod(mode);
        var returnKeyword = method.ReturnsVoid ? string.Empty : "return ";
        var parameters = Join(method.Parameters.Select(p => p.Declaration));
        var arguments = Join(method.Parameters.Select(p => p.Argument));
        var receiver = method.IsStatic ? string.Empty : method.ContainingType + " @this";
        var receiverArgument = method.IsStatic ? string.Empty : "@this";
        var call = $"{(method.IsStatic ? method.ContainingType : "@this")}.{method.MethodName}({arguments})";

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine($"// Pledge contract checks for {method.MemberName}. Edits are lost on the next build.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        foreach (var directive in method.Usings)
        {
            builder.AppendLine(directive);
        }

        builder.AppendLine();
        builder.AppendLine($"namespace {Namespace}");
        builder.AppendLine("{");
        builder.AppendLine($"    file static class {method.ClassName}");
        builder.AppendLine("    {");

        for (var i = 0; i < callSites.Count; i++)
        {
            var site = callSites[i];
            builder.AppendLine("        [global::System.Diagnostics.DebuggerStepThrough]");
            builder.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({site.Version}, {Literal(site.Data)})]");
            builder.AppendLine($"        public static {method.ReturnType} __Intercept{i}({Join(method.IsStatic ? string.Empty : "this " + receiver, parameters)})");
            builder.AppendLine("        {");
            builder.AppendLine($"#line {site.Line} \"{site.FilePath}\"");
            builder.AppendLine($"            {returnKeyword}__Checked({Join(receiverArgument, arguments)});");
            builder.AppendLine("#line default");
            builder.AppendLine("        }");
            builder.AppendLine();
        }

        builder.AppendLine($"        private static {method.ReturnType} __Checked({Join(receiver, parameters, CallerParameters)})");
        builder.AppendLine("        {");
        foreach (var contract in method.Contracts.Where(contract => contract.Kind == ContractKind.Precondition))
        {
            AppendCheck(builder, method, contract, report, thrown: null, indent: "            ");
        }

        if (!method.WrapsBody)
        {
            builder.AppendLine($"            {returnKeyword}{call};");
        }
        else
        {
            foreach (var snapshot in method.Snapshots)
            {
                builder.AppendLine($"#line {snapshot.Site.Line} \"{snapshot.Site.FilePath}\"");
                builder.AppendLine($"            {snapshot.Type} {snapshot.Name} = ({snapshot.Expression});");
                builder.AppendLine("#line default");
            }

            if (method.AsyncKind == AsyncKind.None)
            {
                AppendBody(builder, method, call, report, isAsync: false);
            }
            else
            {
                var snapshotArguments = Join(method.Snapshots.Select(snapshot => snapshot.Name));
                builder.AppendLine($"            return __Awaited({Join(receiverArgument, arguments, snapshotArguments, "__callerFilePath, __callerLineNumber")});");
            }
        }

        builder.AppendLine("        }");

        if (method.WrapsBody && method.AsyncKind != AsyncKind.None)
        {
            var snapshotParameters = Join(method.Snapshots.Select(snapshot => $"{snapshot.Type} {snapshot.Name}"));
            builder.AppendLine();
            builder.AppendLine($"        private static async {method.ReturnType} __Awaited({Join(receiver, parameters, snapshotParameters, "string __callerFilePath, int __callerLineNumber")})");
            builder.AppendLine("        {");
            AppendBody(builder, method, call, report, isAsync: true);
            builder.AppendLine("        }");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("namespace System.Runtime.CompilerServices");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        builder.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute");
        builder.AppendLine("    {");
        builder.AppendLine("        public InterceptsLocationAttribute(int version, string data)");
        builder.AppendLine("        {");
        builder.AppendLine("            _ = version;");
        builder.AppendLine("            _ = data;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    // The original call inside a try, EnsuresOnThrow clauses derived-first so every catch is reachable, then the
    // postconditions. Cancellation bypasses the on-throw checks unless a contract names a cancellation exception.
    private static void AppendBody(StringBuilder builder, ContractedMethod method, string call, string report, bool isAsync)
    {
        var await = isAsync ? "await " : string.Empty;
        if (method.HasResult)
        {
            builder.AppendLine($"            {method.ResultType} __result;");
        }

        var onThrow = method.Contracts.Where(contract => contract.Kind == ContractKind.PostconditionOnThrow).ToList();
        if (onThrow.Count == 0)
        {
            // Nothing to check on the way out, so no try: an exception from the body simply skips the postconditions.
            builder.AppendLine(method.HasResult ? $"            __result = {await}{call};" : $"            {await}{call};");
        }
        else
        {
            builder.AppendLine("            try");
            builder.AppendLine("            {");
            builder.AppendLine(method.HasResult ? $"                __result = {await}{call};" : $"                {await}{call};");
            builder.AppendLine("            }");
        }

        if (onThrow.Count > 0 && !method.OnThrowCoversCancellation)
        {
            builder.AppendLine("            catch (global::System.OperationCanceledException)");
            builder.AppendLine("            {");
            builder.AppendLine("                throw;");
            builder.AppendLine("            }");
        }

        foreach (var clause in onThrow.GroupBy(contract => contract.ExceptionType!, StringComparer.Ordinal).OrderByDescending(group => group.First().ExceptionDepth).ThenBy(group => group.Key, StringComparer.Ordinal))
        {
            builder.AppendLine($"            catch ({clause.Key} __pledgeThrown)");
            builder.AppendLine("            {");
            foreach (var contract in clause)
            {
                AppendCheck(builder, method, contract, report, thrown: "__pledgeThrown", indent: "                ");
            }

            builder.AppendLine("                throw;");
            builder.AppendLine("            }");
        }

        builder.AppendLine();
        foreach (var contract in method.Contracts.Where(contract => contract.Kind == ContractKind.Postcondition))
        {
            AppendCheck(builder, method, contract, report, thrown: null, indent: "            ");
        }

        if (method.HasResult)
        {
            builder.AppendLine("            return __result;");
        }
    }

    private static void AppendCheck(StringBuilder builder, ContractedMethod method, ContractModel contract, string report, string? thrown, string indent)
    {
        var ok = "__pledgeOk" + contract.Index;
        var line = $"#line {contract.Site.Line} \"{contract.Site.FilePath}\"";

        builder.AppendLine($"{indent}bool {ok};");
        builder.AppendLine($"{indent}try");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine(line);
        builder.AppendLine($"{indent}    {ok} = ({contract.Expression});");
        builder.AppendLine("#line default");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine($"{indent}catch (global::System.Exception __pledgeCause)");
        builder.AppendLine($"{indent}{{");
        AppendReport(builder, method, contract, report, thrown, cause: "__pledgeCause", indent: indent + "    ");
        builder.AppendLine($"{indent}    {ok} = true;");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine();
        builder.AppendLine($"{indent}if (!{ok})");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine(line);
        AppendReport(builder, method, contract, report, thrown, cause: null, indent: indent + "    ");
        builder.AppendLine("#line default");
        builder.AppendLine($"{indent}}}");
        builder.AppendLine();
    }

    private static void AppendReport(StringBuilder builder, ContractedMethod method, ContractModel contract, string report, string? thrown, string? cause, string indent)
    {
        builder.AppendLine($"{indent}{report}(new global::PledgeContracts.PledgeViolation");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    Kind = global::PledgeContracts.PledgeKind.{contract.PledgeKind},");
        builder.AppendLine($"{indent}    Expression = {Literal(contract.Text)},");
        builder.AppendLine($"{indent}    Member = {Literal(method.MemberName)},");
        builder.AppendLine($"{indent}    Message = {contract.Message ?? "null"},");
        builder.AppendLine($"{indent}    CallerFilePath = __callerFilePath,");
        builder.AppendLine($"{indent}    CallerLineNumber = __callerLineNumber,");
        if (thrown is not null)
        {
            builder.AppendLine($"{indent}    Thrown = {thrown},");
        }

        if (cause is not null)
        {
            builder.AppendLine($"{indent}    Cause = {cause},");
        }

        builder.AppendLine($"{indent}}});");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Join(params string[] parts) => string.Join(", ", parts.Where(part => part.Length > 0));

    private static string Join(IEnumerable<string> parts) => string.Join(", ", parts);
}
